# Program 26: Write a program to check month names based on month number.

month = int(input("Enter month number (1-12): "))

if month == 1:
    print("Month: January")
elif month == 2:
    print("Month: February")
elif month == 3:
    print("Month: March")
elif month == 4:
    print("Month: April")
elif month == 5:
    print("Month: May")
elif month == 6:
    print("Month: June")
elif month == 7:
    print("Month: July")
elif month == 8:
    print("Month: August")
elif month == 9:
    print("Month: September")
elif month == 10:
    print("Month: October")
elif month == 11:
    print("Month: November")
elif month == 12:
    print("Month: December")
else:
    print("Invalid month number")




    